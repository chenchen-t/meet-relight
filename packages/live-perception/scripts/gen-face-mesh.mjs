// Converts MediaPipe's canonical_face_model.obj (Apache-2.0, google-ai-edge/mediapipe)
// into a compact TS module: canonical positions (cm), UVs and triangle indices.
// Usage: node scripts/gen-face-mesh.mjs path/to/canonical_face_model.obj
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = readFileSync(process.argv[2], 'utf8');
const v = [];
const vt = [];
const f = [];
for (const line of src.split('\n')) {
  const p = line.trim().split(/\s+/);
  if (p[0] === 'v') v.push(p.slice(1, 4).map(Number));
  else if (p[0] === 'vt') vt.push(p.slice(1, 3).map(Number));
  else if (p[0] === 'f') {
    const tri = p.slice(1, 4).map((s) => s.split('/').map(Number));
    f.push(tri.map(([vi, ti]) => [vi - 1, ti - 1]));
  }
}
// Per-vertex UV (each vertex must map to a single vt).
const uv = new Array(v.length).fill(null);
for (const tri of f) {
  for (const [vi, ti] of tri) {
    if (uv[vi] && (uv[vi][0] !== vt[ti][0] || uv[vi][1] !== vt[ti][1])) throw new Error(`UV seam at vertex ${vi}`);
    uv[vi] = vt[ti];
  }
}
if (uv.some((x) => !x)) throw new Error('vertex without UV');
const tris = f.map((t) => t.map(([vi]) => vi));
const r = (x) => +x.toFixed(5);
const out = `// AUTO-GENERATED by scripts/gen-face-mesh.mjs from MediaPipe canonical_face_model.obj
// (Apache-2.0, https://github.com/google-ai-edge/mediapipe). Do not edit.
export const FACE_VERTEX_COUNT = ${v.length};
/** Canonical face positions in cm, xyz interleaved (+y up, +z towards camera). */
export const CANONICAL_POSITIONS = new Float32Array([${v.flat().map(r).join(',')}]);
/** Canonical face UVs (u right, v up as in the .obj), uv interleaved, per vertex. */
export const CANONICAL_UVS = new Float32Array([${uv.flat().map(r).join(',')}]);
/** Triangle list (${tris.length} triangles), counter-clockwise in canonical space. */
export const FACE_TRIANGLES = new Uint16Array([${tris.flat().join(',')}]);
`;
const dst = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'faceMeshData.ts');
writeFileSync(dst, out);
console.log(`wrote ${dst}: ${v.length} verts, ${f.length} tris`);
